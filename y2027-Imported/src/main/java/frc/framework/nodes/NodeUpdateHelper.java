package frc.framework.nodes;

import frc.framework.execution.ExecutionManager;
import frc.framework.execution.NodeCachableResult;
import frc.framework.execution.TimestampedValue;

/**
 * Provides tools for nodes to handle inputs and outputs
 */
public class NodeUpdateHelper {
	private final ExecutionManager executionManager;
	private final NodeInformation nodeInformation;
	private final Node node;
	private final NodeCachableResult cachableResult;
	
	/**
	 * Construct an update helper
	 *
	 * @param node             The node that is receiving and giving data
	 * @param nodeInformation  The information generated by the node during its configuration step
	 * @param executionManager A reference to the current execution manager
	 * @param result           A cachable result to write output data to
	 */
	public NodeUpdateHelper(
		Node node, NodeInformation nodeInformation, ExecutionManager executionManager, NodeCachableResult result
	) {
		this.node = node;
		this.nodeInformation = nodeInformation;
		this.executionManager = executionManager;
		this.cachableResult = result;
	}
	
	/**
	 * Get the evaluation of a given value
	 *
	 * @param identifier The identifier of the value one is attempting to access
	 * @param <T>        The type of the value
	 *
	 * @return The current value associated with the identifier
	 */
	@SuppressWarnings(
		"unchecked"
	)
	public <T> TimestampedValue<T> getValue(ValueIdentifier<T> identifier) {
		if (!nodeInformation.getInputIds().contains(identifier.getId())) {
			throw new UndeclaredReadException(node, identifier);
		}
		
		TimestampedValue<?> result = cachableResult.get(executionManager, identifier.getId());
		
		if (!identifier.getType().isInstance(result.getValue())) {
			throw new ClassCastException(
				"Attempted to get a value of type " + identifier.getType()
					.getName() + ", but the value we got is of type " + result.getValue().getClass()
			);
		}
		
		return (TimestampedValue<T>) result;
	}
	
	/**
	 * Output to a given value identifier
	 *
	 * @param identifier The identifier of the value this node is outputting to
	 * @param value      The value to be associated with the identifier
	 * @param <T>        The type of the value
	 */
	public <T> void setValue(ValueIdentifier<T> identifier, T value) {
		setValue(identifier, value, Priority.Default);
	}
	
	/**
	 * Output to a given value identifier
	 *
	 * @param identifier The identifier of the value this node is outputting to
	 * @param value      The value to be associated with the identifier
	 * @param priority   The priority of the value, higher {@link Priority#value} beats lower
	 * @param <T>        The type of the value
	 */
	public <T> void setValue(ValueIdentifier<T> identifier, T value, Priority priority) {
		if (!nodeInformation.getOutputIds().contains(identifier.getId())) {
			throw new UndeclaredWriteException(node, identifier);
		}
		
		cachableResult.set(identifier.getId(), value, priority);
	}
}
